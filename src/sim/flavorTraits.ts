export function rollFlavors(count: number): string[] {
  const picked = new Set<string>();
  const max = Math.min(count, FLAVOR_TRAITS.length);
  while (picked.size < max) {
    picked.add(FLAVOR_TRAITS[Math.floor(Math.random() * FLAVOR_TRAITS.length)]!);
  }
  return [...picked];
}

export function rollFlavorCount(): number {
  // 2〜4 個。平均 3 個。
  const r = Math.random();
  if (r < 0.25) return 2;
  if (r < 0.75) return 3;
  return 4;
}
