function pickFromPool(pool: string[]): string {
  return pool[Math.floor(Math.random() * pool.length)]!;
}

function pickLine(c: Chibiwafu): string {
  // 無口：85% は沈黙
  if (c.traits.includes('mukuchi') && Math.random() < 0.85) return pickFromPool(TRAIT_LINES.mukuchi!);
  // 特性持ちは 60% で特性セリフ
  for (const t of c.traits) {
    const pool = TRAIT_LINES[t];
    if (pool && Math.random() < 0.6) return pickFromPool(pool);
  }
  // 残りは 10% で叫び、90% で汎用
  if (Math.random() < 0.1) return pickFromPool(EXCLAMATIONS);
  return pickFromPool(GENERIC_LINES);
}

// 独り言：特性セリフも汎用も混ぜて、少しランダム性を上げる。
export function pickOshaberiLine(c?: Chibiwafu): string {
  if (c) return pickLine(c);
  return pickFromPool(GENERIC_LINES);
}

export interface ChatAttempt {
  a: Chibiwafu;
  b: Chibiwafu;
  lineA: string;
  lineB: string;
  duration: number;
}

export function maybeStartChat(c1: Chibiwafu, c2: Chibiwafu): ChatAttempt | null {
  if (c1.chatCooldown > 0 || c2.chatCooldown > 0) return null;
  if (c1.state !== 'idle' && c1.state !== 'surprised') return null;
  if (c2.state !== 'idle' && c2.state !== 'surprised') return null;
  if (Math.random() > derivedChatChance(c1.params, c2.params)) return null;
  return {
    a: c1,
    b: c2,
    lineA: pickLine(c1),
    lineB: pickLine(c2),
    duration: 2.2 + Math.random() * 1.3,
  };
}
